const locales = { en, tr };
let current = en;

export function setLocale(name) { current = locales[name] || en; }
export function addLocale(name, dict) { locales[name] = { ...en, ...dict }; }
export function msg(key, ...args) {
  const m = current[key] ?? en[key];
  return typeof m === 'function' ? m(...args) : m;
}
